// Turns tokens/little-lantern.tokens.json into:
//   tokens/tokens.css  (CSS custom properties for HTML examples)
//   tokens/tokens.js   (plain JS object for GSAP / Remotion)
// Run: node scripts/build-tokens.mjs   (no npm install needed)
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../tokens/little-lantern.tokens.json", import.meta.url)));

const flat = {};            // "color-cream" -> value
const walk = (node, path) => {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (val && typeof val === "object" && "$value" in val) flat[[...path, key].join("-")] = val.$value;
    else if (val && typeof val === "object") walk(val, [...path, key]);
  }
};
walk(src, []);

// Resolve aliases like "{color.ink}"
const resolve = (v) => (typeof v === "string" && v.startsWith("{") ? resolve(flat[v.slice(1, -1).replaceAll(".", "-")]) : v);

const toCss = (v) => {
  v = resolve(v);
  if (Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === "number")) return `cubic-bezier(${v.join(", ")})`;
  if (Array.isArray(v)) return v.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ");
  if (v && typeof v === "object" && "hex" in v) return v.hex;
  if (v && typeof v === "object" && "unit" in v) return `${v.value}${v.unit}`;
  return String(v);
};

const css = [":root {", ...Object.entries(flat).map(([k, v]) => `  --${k}: ${toCss(v)};`), "}", ""].join("\n");
writeFileSync(new URL("../tokens/tokens.css", import.meta.url), "/* Generated by scripts/build-tokens.mjs - do not edit by hand */\n" + css);

const js = Object.fromEntries(Object.entries(flat).map(([k, v]) => [k, toCss(v)]));
js.spring = src.motion.spring.$extensions["dev.codedmotion.spring"];
js.video = src.motion.video.$extensions["dev.codedmotion.video"];
js.easingArrays = Object.fromEntries(Object.entries(src.motion.easing).filter(([k]) => !k.startsWith("$")).map(([k, v]) => [k, v.$value]));
writeFileSync(new URL("../tokens/tokens.js", import.meta.url),
  "// Generated by scripts/build-tokens.mjs - do not edit by hand\nexport const tokens = " + JSON.stringify(js, null, 2) + ";\n");
console.log(`Wrote ${Object.keys(flat).length} tokens to tokens/tokens.css and tokens/tokens.js`);
